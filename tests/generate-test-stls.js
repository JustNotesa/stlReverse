/**
 * Generiert Test-STL-Dateien mit bekannten Geometrien:
 * - Kegel (spitz, abgestumpft, flach, steil)
 * - Kugel (voll, Halbkugel)
 * - Schräger Zylinder (45°)
 */
import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const samplesDir = join(__dirname, '..', 'samples');

// --- Binary STL Writer ---
function writeBinaryStl(faces, path) {
  const headerSize = 80;
  const faceCountSize = 4;
  const faceRecordSize = 50; // 12 floats (normal + 3 vertices) * 4 bytes + 2 attribute bytes
  const bufSize = headerSize + faceCountSize + faces.length * faceRecordSize;
  const buf = Buffer.alloc(bufSize);

  // Header (80 bytes, zero-filled)
  buf.write('Generated by STL Reverse Test Suite', 0, 'ascii');
  // Face count
  buf.writeUInt32LE(faces.length, 80);

  let offset = 84;
  for (const face of faces) {
    const { normal, vertices } = face;
    // Normal
    buf.writeFloatLE(normal[0], offset); offset += 4;
    buf.writeFloatLE(normal[1], offset); offset += 4;
    buf.writeFloatLE(normal[2], offset); offset += 4;
    // 3 Vertices
    for (const v of vertices) {
      buf.writeFloatLE(v[0], offset); offset += 4;
      buf.writeFloatLE(v[1], offset); offset += 4;
      buf.writeFloatLE(v[2], offset); offset += 4;
    }
    // Attribute byte count
    buf.writeUInt16LE(0, offset); offset += 2;
  }

  writeFileSync(path, buf);
  console.log(`  ${path} — ${faces.length} faces, ${bufSize} bytes`);
}

// --- Geometry Helpers ---
function computeNormal(v0, v1, v2) {
  const ax = v1[0] - v0[0], ay = v1[1] - v0[1], az = v1[2] - v0[2];
  const bx = v2[0] - v0[0], by = v2[1] - v0[1], bz = v2[2] - v0[2];
  const nx = ay * bz - az * by;
  const ny = az * bx - ax * bz;
  const nz = ax * by - ay * bx;
  const len = Math.hypot(nx, ny, nz) || 1;
  return [nx / len, ny / len, nz / len];
}

function makeFace(v0, v1, v2) {
  return { normal: computeNormal(v0, v1, v2), vertices: [v0, v1, v2] };
}

function makeFaceWithNormal(v0, v1, v2, normal) {
  const len = Math.hypot(normal[0], normal[1], normal[2]) || 1;
  return { normal: [normal[0] / len, normal[1] / len, normal[2] / len], vertices: [v0, v1, v2] };
}

// --- Axial Cylinder Generator (Z-axis, with ring subdivisions) ---
function generateCylinder(radius, height, segments, rings = 8, centerX = 0, centerY = 0, centerZ = 0) {
  const faces = [];
  // Lateral surface with rings
  for (let r = 0; r < rings; r++) {
    const z0 = centerZ + (height * r) / rings;
    const z1 = centerZ + (height * (r + 1)) / rings;
    for (let i = 0; i < segments; i++) {
      const a0 = (2 * Math.PI * i) / segments;
      const a1 = (2 * Math.PI * (i + 1)) / segments;
      const cos0 = Math.cos(a0), sin0 = Math.sin(a0);
      const cos1 = Math.cos(a1), sin1 = Math.sin(a1);

      const p00 = [centerX + radius * cos0, centerY + radius * sin0, z0];
      const p01 = [centerX + radius * cos1, centerY + radius * sin1, z0];
      const p10 = [centerX + radius * cos0, centerY + radius * sin0, z1];
      const p11 = [centerX + radius * cos1, centerY + radius * sin1, z1];

      // Outward normals for lateral surface
      const n0 = [cos0, sin0, 0];
      const n1 = [cos1, sin1, 0];
      const nMid = [(cos0 + cos1) / 2, (sin0 + sin1) / 2, 0];
      faces.push(makeFaceWithNormal(p00, p01, p11, nMid));
      faces.push(makeFaceWithNormal(p00, p11, p10, nMid));
    }
  }
  // Bottom cap (normal pointing down)
  const bc = [centerX, centerY, centerZ];
  for (let i = 0; i < segments; i++) {
    const a0 = (2 * Math.PI * i) / segments;
    const a1 = (2 * Math.PI * (i + 1)) / segments;
    const b0 = [centerX + radius * Math.cos(a0), centerY + radius * Math.sin(a0), centerZ];
    const b1 = [centerX + radius * Math.cos(a1), centerY + radius * Math.sin(a1), centerZ];
    faces.push(makeFaceWithNormal(b1, b0, bc, [0, 0, -1]));
  }
  // Top cap (normal pointing up)
  const tc = [centerX, centerY, centerZ + height];
  for (let i = 0; i < segments; i++) {
    const a0 = (2 * Math.PI * i) / segments;
    const a1 = (2 * Math.PI * (i + 1)) / segments;
    const t0 = [centerX + radius * Math.cos(a0), centerY + radius * Math.sin(a0), centerZ + height];
    const t1 = [centerX + radius * Math.cos(a1), centerY + radius * Math.sin(a1), centerZ + height];
    faces.push(makeFaceWithNormal(t0, t1, tc, [0, 0, 1]));
  }
  return faces;
}

// --- Cone Generator (with ring subdivisions for realistic tesselation) ---
function generateCone(radiusBottom, radiusTop, height, segments, rings = 8, centerX = 0, centerY = 0, centerZ = 0) {
  const faces = [];
  for (let r = 0; r < rings; r++) {
    const t0 = r / rings;
    const t1 = (r + 1) / rings;
    const z0 = centerZ + height * t0;
    const z1 = centerZ + height * t1;
    const r0 = radiusBottom + (radiusTop - radiusBottom) * t0;
    const r1 = radiusBottom + (radiusTop - radiusBottom) * t1;

    for (let i = 0; i < segments; i++) {
      const a0 = (2 * Math.PI * i) / segments;
      const a1 = (2 * Math.PI * (i + 1)) / segments;
      const cos0 = Math.cos(a0), sin0 = Math.sin(a0);
      const cos1 = Math.cos(a1), sin1 = Math.sin(a1);

      const p00 = [centerX + r0 * cos0, centerY + r0 * sin0, z0];
      const p01 = [centerX + r0 * cos1, centerY + r0 * sin1, z0];
      const p10 = [centerX + r1 * cos0, centerY + r1 * sin0, z1];
      const p11 = [centerX + r1 * cos1, centerY + r1 * sin1, z1];

      if (r1 < 0.001) {
        // Top ring converges to apex
        const apex = [centerX, centerY, z1];
        faces.push(makeFace(p00, p01, apex));
      } else {
        faces.push(makeFace(p00, p01, p11));
        faces.push(makeFace(p00, p11, p10));
      }
    }
  }

  // Bottom cap
  const bc = [centerX, centerY, centerZ];
  for (let i = 0; i < segments; i++) {
    const a0 = (2 * Math.PI * i) / segments;
    const a1 = (2 * Math.PI * (i + 1)) / segments;
    const b0 = [centerX + radiusBottom * Math.cos(a0), centerY + radiusBottom * Math.sin(a0), centerZ];
    const b1 = [centerX + radiusBottom * Math.cos(a1), centerY + radiusBottom * Math.sin(a1), centerZ];
    faces.push(makeFace(b1, b0, bc));
  }

  // Top cap (if frustum)
  if (radiusTop > 0.001) {
    const tc = [centerX, centerY, centerZ + height];
    for (let i = 0; i < segments; i++) {
      const a0 = (2 * Math.PI * i) / segments;
      const a1 = (2 * Math.PI * (i + 1)) / segments;
      const t0 = [centerX + radiusTop * Math.cos(a0), centerY + radiusTop * Math.sin(a0), centerZ + height];
      const t1 = [centerX + radiusTop * Math.cos(a1), centerY + radiusTop * Math.sin(a1), centerZ + height];
      faces.push(makeFace(t0, t1, tc));
    }
  }
  return faces;
}

// --- Sphere Generator (with explicit outward normals) ---
function generateSphere(radius, stacks, slices, centerX = 0, centerY = 0, centerZ = 0) {
  const faces = [];
  const v = (phi, theta) => [
    centerX + radius * Math.sin(phi) * Math.cos(theta),
    centerY + radius * Math.sin(phi) * Math.sin(theta),
    centerZ + radius * Math.cos(phi)
  ];
  // Outward normal = (point - center) / radius
  const outwardNormal = (pt) => [
    (pt[0] - centerX) / radius,
    (pt[1] - centerY) / radius,
    (pt[2] - centerZ) / radius
  ];
  const avgNormal = (...pts) => {
    const n = [0, 0, 0];
    pts.forEach(p => { n[0] += p[0]; n[1] += p[1]; n[2] += p[2]; });
    const len = Math.hypot(n[0], n[1], n[2]) || 1;
    return [n[0] / len, n[1] / len, n[2] / len];
  };

  for (let i = 0; i < stacks; i++) {
    const phi0 = (Math.PI * i) / stacks;
    const phi1 = (Math.PI * (i + 1)) / stacks;
    for (let j = 0; j < slices; j++) {
      const theta0 = (2 * Math.PI * j) / slices;
      const theta1 = (2 * Math.PI * (j + 1)) / slices;

      const p00 = v(phi0, theta0);
      const p01 = v(phi0, theta1);
      const p10 = v(phi1, theta0);
      const p11 = v(phi1, theta1);

      if (i === 0) {
        // North pole cap — use average outward normal of the non-pole vertices
        const normal = avgNormal(outwardNormal(p00), outwardNormal(p11), outwardNormal(p10));
        faces.push(makeFaceWithNormal(p00, p11, p10, normal));
      } else if (i === stacks - 1) {
        // South pole cap
        const normal = avgNormal(outwardNormal(p00), outwardNormal(p01), outwardNormal(p10));
        faces.push(makeFaceWithNormal(p00, p01, p10, normal));
      } else {
        const n1 = avgNormal(outwardNormal(p00), outwardNormal(p01), outwardNormal(p11));
        faces.push(makeFaceWithNormal(p00, p01, p11, n1));
        const n2 = avgNormal(outwardNormal(p00), outwardNormal(p11), outwardNormal(p10));
        faces.push(makeFaceWithNormal(p00, p11, p10, n2));
      }
    }
  }
  return faces;
}

// --- Hemisphere Generator ---
function generateHemisphere(radius, stacks, slices, centerX = 0, centerY = 0, centerZ = 0) {
  const faces = [];
  const halfStacks = Math.ceil(stacks / 2);
  for (let i = 0; i < halfStacks; i++) {
    const phi0 = (Math.PI * i) / stacks;
    const phi1 = (Math.PI * (i + 1)) / stacks;
    for (let j = 0; j < slices; j++) {
      const theta0 = (2 * Math.PI * j) / slices;
      const theta1 = (2 * Math.PI * (j + 1)) / slices;

      const v = (phi, theta) => [
        centerX + radius * Math.sin(phi) * Math.cos(theta),
        centerY + radius * Math.sin(phi) * Math.sin(theta),
        centerZ + radius * Math.cos(phi)
      ];

      const p00 = v(phi0, theta0);
      const p01 = v(phi0, theta1);
      const p10 = v(phi1, theta0);
      const p11 = v(phi1, theta1);

      if (i === 0) {
        faces.push(makeFace(p00, p11, p10));
      } else {
        faces.push(makeFace(p00, p01, p11));
        faces.push(makeFace(p00, p11, p10));
      }
    }
  }
  // Bottom flat cap
  const bottomZ = centerZ + radius * Math.cos(Math.PI * halfStacks / stacks);
  for (let j = 0; j < slices; j++) {
    const theta0 = (2 * Math.PI * j) / slices;
    const theta1 = (2 * Math.PI * (j + 1)) / slices;
    const phi = (Math.PI * halfStacks) / stacks;
    const p0 = [
      centerX + radius * Math.sin(phi) * Math.cos(theta0),
      centerY + radius * Math.sin(phi) * Math.sin(theta0),
      bottomZ
    ];
    const p1 = [
      centerX + radius * Math.sin(phi) * Math.cos(theta1),
      centerY + radius * Math.sin(phi) * Math.sin(theta1),
      bottomZ
    ];
    const center = [centerX, centerY, bottomZ];
    faces.push(makeFace(p1, p0, center));
  }
  return faces;
}

// --- Oblique Cylinder Generator ---
function generateObliqueCylinder(radius, length, axisVec, segments, rings, centerX = 0, centerY = 0, centerZ = 0) {
  const faces = [];
  const len = Math.hypot(axisVec[0], axisVec[1], axisVec[2]);
  const axis = axisVec.map(v => v / len);

  // Find two perpendicular vectors to axis
  let up = [0, 0, 1];
  if (Math.abs(axis[2]) > 0.9) up = [1, 0, 0];
  const u = (() => {
    const c = [
      axis[1] * up[2] - axis[2] * up[1],
      axis[2] * up[0] - axis[0] * up[2],
      axis[0] * up[1] - axis[1] * up[0]
    ];
    const l = Math.hypot(...c);
    return c.map(v => v / l);
  })();
  const v = [
    axis[1] * u[2] - axis[2] * u[1],
    axis[2] * u[0] - axis[0] * u[2],
    axis[0] * u[1] - axis[1] * u[0]
  ];

  const point = (t, angle) => {
    const cos = Math.cos(angle), sin = Math.sin(angle);
    return [
      centerX + axis[0] * t + radius * (u[0] * cos + v[0] * sin),
      centerY + axis[1] * t + radius * (u[1] * cos + v[1] * sin),
      centerZ + axis[2] * t + radius * (u[2] * cos + v[2] * sin)
    ];
  };

  for (let r = 0; r < rings; r++) {
    const t0 = (length * r) / rings;
    const t1 = (length * (r + 1)) / rings;
    for (let s = 0; s < segments; s++) {
      const a0 = (2 * Math.PI * s) / segments;
      const a1 = (2 * Math.PI * (s + 1)) / segments;
      const p00 = point(t0, a0);
      const p01 = point(t0, a1);
      const p10 = point(t1, a0);
      const p11 = point(t1, a1);
      faces.push(makeFace(p00, p01, p11));
      faces.push(makeFace(p00, p11, p10));
    }
  }

  // End caps
  for (const t of [0, length]) {
    const center = [centerX + axis[0] * t, centerY + axis[1] * t, centerZ + axis[2] * t];
    for (let s = 0; s < segments; s++) {
      const a0 = (2 * Math.PI * s) / segments;
      const a1 = (2 * Math.PI * (s + 1)) / segments;
      const p0 = point(t, a0);
      const p1 = point(t, a1);
      if (t === 0) {
        faces.push(makeFace(p1, p0, center));
      } else {
        faces.push(makeFace(p0, p1, center));
      }
    }
  }
  return faces;
}

